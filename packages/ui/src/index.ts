function documentLocale(): Locale {
  if (typeof document !== "undefined" && document.documentElement.lang === "en") return "en";
  if (typeof process !== "undefined" && process.env.NEXT_PUBLIC_FORGEFLOW_LOCALE === "en") return "en";
  return "vi";
}

export function translate(key: string, values: Record<string, string | number> = {}, locale: Locale = documentLocale()): string {
  const template = messages[locale][key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function statusLabel(status: string, locale: Locale = documentLocale()): string {
  if (locale === "vi" && labels[status]) return labels[status];
  return status.replaceAll("_", " ").toLowerCase().replace(/\b\w/g, (letter) => letter.toUpperCase());
}

const readinessFieldKeys: Record<string, string> = {
  TITLE: "backlog.title",
  SUMMARY: "spec.summary",
  PROBLEM_STATEMENT: "spec.problem-statement",
  EXPECTED_BEHAVIOR: "spec.expected-behavior",
  ACTUAL_BEHAVIOR: "spec.actual-behavior",
  ENVIRONMENT: "spec.environment",
  PRECONDITIONS: "spec.preconditions",
  FREQUENCY: "spec.frequency",
  AFFECTED_VERSION: "spec.affected-version",
  GOAL: "spec.goal",
  BUSINESS_IMPACT: "spec.business-impact",
  NO_CODE_CHANGE_RATIONALE: "spec.no-code-rationale",
};

const reproductionFieldKeys: Record<string, string> = {
  ACTION: "spec.action",
  EXPECTED_RESULT: "spec.expected-result",
  OBSERVED_RESULT: "spec.observed-result",
};

export function readinessLabel(missing: string, locale: Locale = documentLocale()): string {
  const fieldKey = readinessFieldKeys[missing];
  if (fieldKey) return translate("readiness.missing-field", { field: translate(fieldKey, {}, locale) }, locale);

  const verifiedField = missing.match(/^HUMAN_VERIFIED_(.+)$/)?.[1];
  if (verifiedField && readinessFieldKeys[verifiedField]) {
    return translate("readiness.human-verification", { field: translate(readinessFieldKeys[verifiedField], {}, locale) }, locale);
  }

  const reproductionField = missing.match(/^REPRODUCTION_STEP_(\d+)_(ACTION|EXPECTED_RESULT|OBSERVED_RESULT)$/);
  if (reproductionField) {
    return translate("readiness.missing-step-field", { index: reproductionField[1], field: translate(reproductionFieldKeys[reproductionField[2]], {}, locale) }, locale);
  }

  const reproductionVerification = missing.match(/^REPRODUCTION_STEP_(\d+)_HUMAN_VERIFIED$/);
  if (reproductionVerification) return translate("readiness.step-verification", { index: reproductionVerification[1] }, locale);
  const criterion = missing.match(/^ACCEPTANCE_CRITERION_(\d+)$/);
  if (criterion) return translate("readiness.criterion-field", { index: criterion[1] }, locale);
  const criterionVerification = missing.match(/^HUMAN_VERIFIED_ACCEPTANCE_CRITERION_(\d+)$/);
  if (criterionVerification) return translate("readiness.criterion-verification", { index: criterionVerification[1] }, locale);

  const directKeys: Record<string, string> = {
    REPOSITORY: "readiness.missing-repository",
    REPRODUCTION_STEP: "readiness.missing-step",
    EVIDENCE: "readiness.missing-evidence",
    AFFECTED_COMPONENT: "readiness.missing-component",
    ACCEPTANCE_CRITERION: "readiness.missing-criterion",
    GOAL_OR_PROBLEM_STATEMENT: "readiness.missing-goal",
    REPOSITORY_OR_NO_CODE_CHANGE_RATIONALE: "readiness.missing-repository-rationale",
  };
  return translate(directKeys[missing] ?? "readiness.unknown", { item: statusLabel(missing, locale) }, locale);
}
